#requires -Version 7.0

<#
.SYNOPSIS
    Post-processes PlatyPS-generated markdown help files.

.DESCRIPTION
    Runs after './build.ps1 -Tasks docs' to clean up common PlatyPS artifacts:

    - Replaces the '{{ Fill ProgressAction Description }}' placeholder with a
      standard description.
    - Populates empty RELATED LINKS sections with the project GitHub URL and
      website.
    - Populates '{{ Fill in the Description }}' and '{{ Fill in the Synopsis }}'
      placeholders on the module index page by reading the SYNOPSIS from each
      cmdlet's markdown file or source function.
    - Reports a summary of changes made.

    Designed to be run from the repository root. Safe to run multiple times
    (idempotent).

.PARAMETER DocsPath
    Path to the PlatyPS markdown help locale folder. Defaults to 'docs/help/en-US'.

.PARAMETER GitHubUrl
    GitHub repository URL. Auto-detected from 'gh repo view' if not provided.

.PARAMETER WebsiteUrl
    Project or author website URL. Defaults to the manifest's PrivateData.PSData.ProjectUri.
    If neither is available, only the GitHub URL is added to RELATED LINKS.

.EXAMPLE
    # Auto-detect everything
    ./Scripts/Update-PlatyPSDocs.ps1

.EXAMPLE
    # Explicit paths
    ./Scripts/Update-PlatyPSDocs.ps1 -DocsPath 'docs/help/en-US' -GitHubUrl 'https://github.com/user/ModuleName'
#>
[CmdletBinding()]
param(
    [Parameter()]
    [string]$DocsPath = (Join-Path (Split-Path -Parent $PSScriptRoot) 'docs/help/en-US'),

    [Parameter()]
    [string]$GitHubUrl,

    [Parameter()]
    [string]$WebsiteUrl
)

$ErrorActionPreference = 'Stop'
$ProjectRoot = Split-Path -Parent $PSScriptRoot
$SourceRoot = Join-Path $ProjectRoot 'source'

# Resolve docs path
if (-not (Test-Path $DocsPath)) {
    Write-Error "Docs path '$DocsPath' not found. Run './build.ps1 -Tasks docs' first."
    return
}

# Auto-detect GitHub URL if not provided
if (-not $GitHubUrl) {
    try {
        $ghJson = gh repo view --json url 2>$null
        if ($LASTEXITCODE -ne 0 -or -not $ghJson) { throw 'gh repo view failed' }
        $GitHubUrl = ($ghJson | ConvertFrom-Json).url
        Write-Verbose "Auto-detected GitHub URL: $GitHubUrl"
    } catch {
        Write-Warning 'Could not auto-detect GitHub URL. RELATED LINKS will not be updated.'
    }
}

$progressActionDesc = 'Determines how the cmdlet responds to progress' +
    ' updates generated by a command. See the ProgressAction common' +
    ' parameter for more information.'

# Discover the module index page (PlatyPS names it <ModuleName>.md)
$moduleIndexFile = Get-ChildItem -Path $DocsPath -Filter '*.md' -File |
    Where-Object {
        $raw = Get-Content -Path $_.FullName -TotalCount 10
        $raw -match 'Module Guid:'
    } |
    Select-Object -First 1

$moduleIndexName = if ($moduleIndexFile) { $moduleIndexFile.Name } else { $null }
Write-Verbose "Module index page: $moduleIndexName"

# Build a synopsis lookup from individual cmdlet markdown files.
# Each cmdlet file has "## SYNOPSIS\n<text>" that we can extract.
$synopsisLookup = @{}
$cmdletFiles = Get-ChildItem -Path $DocsPath -Filter '*.md' -File |
    Where-Object { $_.Name -ne $moduleIndexName }

foreach ($cmdletFile in $cmdletFiles) {
    $cmdletContent = Get-Content -Path $cmdletFile.FullName -Raw
    if ($cmdletContent -match '(?m)^## SYNOPSIS\r?\n(.+?)$') {
        $synopsis = $Matches[1].Trim()
        # Only use it if PlatyPS actually extracted a real synopsis
        if ($synopsis -notmatch '^\{\{') {
            $synopsisLookup[$cmdletFile.BaseName] = $synopsis
        }
    }
}

# If PlatyPS couldn't extract a synopsis, fall back to source .SYNOPSIS
if ($synopsisLookup.Count -eq 0 -or $cmdletFiles.Count -gt $synopsisLookup.Count) {
    $sourcePaths = @((Join-Path $SourceRoot 'Public'), (Join-Path $SourceRoot 'Private'))
    foreach ($srcPath in $sourcePaths) {
        if (-not (Test-Path $srcPath)) { continue }
        $sourceFiles = Get-ChildItem -Path $srcPath -Filter '*.ps1' -Recurse
        foreach ($srcFile in $sourceFiles) {
            $funcName = $srcFile.BaseName
            if ($synopsisLookup.ContainsKey($funcName)) { continue }
            $srcContent = Get-Content -Path $srcFile.FullName -Raw
            # Capture the synopsis paragraph up to a blank line, the next help keyword, or #>
            if ($srcContent -match '(?ms)\.SYNOPSIS[ \t]*\r?\n\s*(.+?)\s*(?=\r?\n\s*(?:\r?\n|\.[A-Z]+\b|#>))') {
                $synopsisLookup[$funcName] = ($Matches[1] -replace '\s+', ' ').Trim()
            }
        }
    }
}

# Auto-detect module description from manifest
$moduleDescription = $null
$manifestFiles = Get-ChildItem -Path $SourceRoot -Filter '*.psd1' -File -ErrorAction SilentlyContinue
foreach ($manifest in $manifestFiles) {
    try {
        $data = Import-PowerShellDataFile -Path $manifest.FullName -ErrorAction Stop
        if (-not $WebsiteUrl -and $data.PrivateData.PSData.ProjectUri) {
            $WebsiteUrl = $data.PrivateData.PSData.ProjectUri
        }
        if ($data.Description) {
            $moduleDescription = $data.Description
            break
        }
    } catch {
        Write-Verbose "Could not read manifest '$($manifest.Name)': $_"
    }
}

$files = Get-ChildItem -Path $DocsPath -Filter '*.md' -File
$stats = @{
    ProgressAction     = 0
    RelatedLinks       = 0
    ModuleDescriptions = 0
    TotalFiles         = $files.Count
}

foreach ($file in $files) {
    $content = Get-Content -Path $file.FullName -Raw
    $modified = $false

    # Replace ProgressAction placeholder
    if ($content -match '\{\{ Fill ProgressAction Description \}\}') {
        $content = $content -replace '\{\{ Fill ProgressAction Description \}\}', $progressActionDesc
        $modified = $true
        $stats.ProgressAction++
    }

    # Populate empty RELATED LINKS (only if section is empty — no links below heading)
    if ($GitHubUrl -and $content -match '(?ms)## RELATED LINKS\r?\n\s*\z') {
        $linksBlock = @"
## RELATED LINKS

[$GitHubUrl]($GitHubUrl)
"@
        if ($WebsiteUrl -and $WebsiteUrl -ne $GitHubUrl) {
            $linksBlock += "`r`n`r`n[$WebsiteUrl]($WebsiteUrl)"
        }
        $content = $content -replace '(?ms)## RELATED LINKS\r?\n\s*\z', $linksBlock
        $modified = $true
        $stats.RelatedLinks++
    }

    # Populate module index page placeholders from cmdlet synopses
    if ($moduleIndexName -and $file.Name -eq $moduleIndexName) {
        $hasPlaceholders = $content -match '\{\{ Fill in the (Description|Synopsis) \}\}'
        if ($hasPlaceholders) {
            # Replace per-cmdlet placeholders with their synopsis
            foreach ($entry in $synopsisLookup.GetEnumerator()) {
                $escapedName = [regex]::Escape($entry.Key)
                $heading = "### \[$escapedName\]\($escapedName\.md\)"
                $placeholder = '\{\{ Fill in the (Description|Synopsis) \}\}'
                $pattern = "(?m)($heading)\r?\n$placeholder"
                $replacement = "`$1`n$($entry.Value)"
                $content = $content -replace $pattern, $replacement
            }

            # Replace only the first remaining placeholder (the module-level description).
            # Leftover per-cmdlet placeholders stay visible rather than getting the module text.
            if ($moduleDescription) {
                $content = [regex]::new('\{\{ Fill in the (Description|Synopsis) \}\}').Replace($content, $moduleDescription.Replace('$', '$$'), 1)
            }

            $modified = $true
            $stats.ModuleDescriptions++
        }
    }

    if ($modified) {
        Set-Content -Path $file.FullName -Value $content -NoNewline -Encoding utf8NoBOM
    }
}

Write-Host "Updated $($stats.TotalFiles) docs in '$DocsPath':" -ForegroundColor Cyan
Write-Host "  ProgressAction placeholders fixed: $($stats.ProgressAction)" -ForegroundColor Green
Write-Host "  RELATED LINKS populated:           $($stats.RelatedLinks)" -ForegroundColor Green
Write-Host "  Module index descriptions filled:  $($stats.ModuleDescriptions)" -ForegroundColor Green
